"""Versioned mail dialogue boundaries, separate from legacy request bytes."""

from typing import Annotated, ClassVar, Literal
from uuid import UUID

from pydantic import ConfigDict, Field

from tanya_bot.conversation_memory import JSONValue
from tanya_bot.schemas import FrozenModel
from tanya_bot.turns import TurnAnswer, TurnRequest, TurnResponse

type PhaseKind = Literal["decide", "final"]


class DialogueModel(FrozenModel):
    """Reject undeclared wire fields at the new protocol boundary."""

    model_config: ClassVar[ConfigDict] = ConfigDict(frozen=True, extra="forbid")


class MailSearch(DialogueModel):
    """One bounded page followed by previews, with no pagination."""

    name: Literal["gmail_search_read"] = "gmail_search_read"
    query: Annotated[str, Field(max_length=512)]
    limit: Annotated[int, Field(ge=1, le=5)]


class MailRead(DialogueModel):
    """Read only references in the authenticated current selection."""

    name: Literal["gmail_read"] = "gmail_read"
    refs: Annotated[tuple[str, ...], Field(min_length=1, max_length=3)]


type MailAction = Annotated[MailSearch | MailRead, Field(discriminator="name")]


class MailCall(DialogueModel):
    """Validated provider proposal; execution still requires owner authority."""

    call_id: Annotated[str, Field(min_length=1, max_length=256)]
    action: MailAction


class MailSource(DialogueModel):
    """An inert preview with a stable reference and a private Gmail binding."""

    ref: Annotated[str, Field(pattern=r"^M[a-f0-9]{12}$")]
    message_id: Annotated[str, Field(pattern=r"^[A-Za-z0-9_-]{1,128}$")]
    subject: Annotated[str, Field(max_length=512)]
    sender: Annotated[str, Field(max_length=512)]
    date: Annotated[str, Field(max_length=128)]
    text: Annotated[str, Field(max_length=4000)]
    truncated: bool


class MailResult(DialogueModel):
    """Bounded untrusted tool data; credentials and attachments are absent."""

    sources: Annotated[tuple[MailSource, ...], Field(max_length=5)] = ()
    query: Annotated[str, Field(max_length=512)] = ""
    has_more: bool = False
    error: Annotated[str | None, Field(max_length=64)] = None
    retrieved_at: Annotated[float, Field(ge=0, allow_inf_nan=False)]


class MailSelection(DialogueModel):
    """A selection is valid only for its owner and current conversation."""

    owner_id: Annotated[int, Field(gt=0)]
    conversation_id: Annotated[int, Field(ge=0)]
    root_id: UUID
    created_at: Annotated[float, Field(ge=0, allow_inf_nan=False)]
    accessed_at: Annotated[float, Field(ge=0, allow_inf_nan=False)]
    result: MailResult
    answer: Annotated[str, Field(max_length=16000)] = ""


class PhaseReceipt(DialogueModel):
    """A completed model phase is immutable and never regenerated by recovery."""

    provider_id: Annotated[str, Field(min_length=1, max_length=256)]
    model: Annotated[str, Field(min_length=1, max_length=128)]
    input_tokens: Annotated[int, Field(ge=0)]
    output_tokens: Annotated[int, Field(ge=0)]
    output: Annotated[tuple[dict[str, JSONValue], ...], Field(max_length=32)]
    answer: TurnAnswer | None = None
    tool: MailCall | None = None


class DialoguePhase(DialogueModel):
    """The bot authorizes a phase; the API claims its exact payload once."""

    kind: PhaseKind
    sent: bool = False
    payload: dict[str, JSONValue] | None = None
    receipt: PhaseReceipt | None = None
    failure: Annotated[str | None, Field(max_length=64)] = None


class MailOperation(DialogueModel):
    """Each Google operation is reserved before I/O and never replayed."""

    key: Annotated[str, Field(min_length=1, max_length=64)]
    completed: bool = False
    ids: Annotated[tuple[str, ...], Field(max_length=5)] = ()
    source: MailSource | None = None
    has_more: bool = False
    failure: Annotated[str | None, Field(max_length=64)] = None


class DialogueRoot(DialogueModel):
    """Frozen owner turn and append-only phase identities live in a v3 sidecar."""

    version: Literal[3] = 3
    turn: TurnRequest
    owner_id: Annotated[int, Field(gt=0)]
    conversation_id: Annotated[int, Field(ge=0)]
    update_id: Annotated[str, Field(min_length=1, max_length=256)]
    model: Annotated[str, Field(min_length=1, max_length=128)]
    created_at: Annotated[float, Field(ge=0, allow_inf_nan=False)]
    cancelled: bool = False
    tainted: bool = False
    selection: MailSelection | None = None
    tool_result: MailResult | None = None
    phases: Annotated[tuple[DialoguePhase, ...], Field(max_length=2)] = ()
    operations: Annotated[tuple[MailOperation, ...], Field(max_length=6)] = ()
    final: TurnResponse | None = None


class PhaseAddress(DialogueModel):
    """The API accepts only an already authorized local phase identity."""

    root_id: UUID
    kind: PhaseKind
