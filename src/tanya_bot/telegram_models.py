class GatewayError(Exception):
    """Root raises a safe code; every failed reserved call remains unresolved."""

    code: str

    def __init__(self, code: str) -> None:
        """Keep safe codes typed while allowing Python exception metadata mutation."""
        self.code = code
        super().__init__(code)

    @override
    def __str__(self) -> str:
        """Exclude provider payloads, tokens and private content from error text."""
        return self.code


GatewayFailure = GatewayError


class VoiceInput(FrozenModel):
    """Bind original media to its conversation across cancellation and restart."""

    update_id: EventId
    request_id: UUID
    conversation_id: ConversationId
    cancelled: bool = False


class Button(FrozenModel):
    """Opaque ASCII callback generated by the core, never by a provider."""

    text: str
    data: str


type Keyboard = tuple[tuple[Button, ...], ...]


class Settings(FrozenModel):
    """Profile matches iOS CharacterProfile and public CompanionProfile."""

    name: Annotated[str, Field(min_length=1, max_length=80)] = "Tanya"
    language: Annotated[str, Field(min_length=1, max_length=40)] = "en"
    profile: CompanionProfile = CompanionProfile()
    voice_replies: bool = False


class Entry(FrozenModel):
    """Stable ids make delete operations independent of list ordering."""

    id: UUID = Field(default_factory=uuid4)
    text: Annotated[str, Field(min_length=1, max_length=16_000)]


class VoiceRequest(FrozenModel):
    """Root owns provider and artifact persistence for this reserved UUID."""

    request_id: UUID
    text: Annotated[str, Field(min_length=1, max_length=16_000)]
    voice: str
    delivery: DeliveryPlan | None = None


class VoiceResult(FrozenModel):
    """Opaque reference to a durable root-owned audio artifact, never a URL."""

    request_id: UUID
    artifact_id: Annotated[str, Field(min_length=1, max_length=512)]


class StoredReply(FrozenModel):
    """Keyboard token is bound to the saved Telegram message id."""

    token: str = Field(default_factory=lambda: uuid4().hex)
    conversation_id: ConversationId = 0
    setting_field: SettingField | None = None
    text: Annotated[str, Field(min_length=1, max_length=16_000)]
    message_id: PositiveId | None = None
    delivery_attempted: bool = False
    kind: Literal["reply", "menu"] = "reply"
    actions: tuple[str, ...] = ()
    remembered: bool = False
    journaled: bool = False
    voice_request: VoiceRequest | None = None
    voice_result: VoiceResult | None = None
    voice_delivery_attempted: bool = False
    voice_cancelled: bool = False
    delivery: DeliveryPlan | None = None
    receipt_only: bool = False


class PendingChat(FrozenModel):
    """A reservation survives cancellation or an unknown provider outcome."""

    update_id: EventId
    conversation_id: ConversationId = 0
    request: ChatRequest
    response: TurnResponse | ChatResponse | None = None
    reply_token: str | None = None
    cancelled: bool = False
    context: TurnContext | None = None


class TelegramState(FrozenModel):
    """Append-only event/request identities prevent replay after restart."""

    version: Literal[1] = 1
    owner_id: PositiveId
    conversation_id: ConversationId = 0
    new_confirmation_token: str | None = None
    settings_menu_token: str | None = None
    settings: Settings = Settings()
    memories: Annotated[tuple[Entry, ...], Field(max_length=256)] = ()
    journal: Annotated[tuple[Entry, ...], Field(max_length=256)] = ()
    history: Annotated[tuple[Entry, ...], Field(max_length=64)] = ()
    history_roles: tuple[Literal["user", "assistant"], ...] = ()
    seen_updates: Annotated[tuple[str, ...], Field(max_length=4096)] = ()
    requests: Annotated[tuple[PendingChat, ...], Field(max_length=1024)] = ()
    voice_inputs: Annotated[tuple[VoiceInput, ...], Field(max_length=4096)] = ()
    replies: Annotated[tuple[StoredReply, ...], Field(max_length=4096)] = ()
    editing: SettingField | None = None
    composing: Literal["memory", "journal"] | None = None
    context: ContextState = ContextState()
    history_barrier: Annotated[tuple[UUID, ...], Field(max_length=64)] = ()

    @model_validator(mode="after")
    def consistent(self) -> Self:
        """Reject corruption that breaks replay or message binding."""
        ids = [item.request.request_id for item in self.requests]
        tokens = [reply.token for reply in self.replies]
        reply_owners = {reply.token: reply.conversation_id for reply in self.replies}
        bad_receipt = any(
            item.response is not None
            and (
                item.response.request_id != item.request.request_id
                or item.reply_token not in tokens
                or reply_owners.get(item.reply_token or "") != item.conversation_id
            )
            for item in self.requests
        )
        confirmation = next(
            (
                reply
                for reply in self.replies
                if reply.token == self.new_confirmation_token
            ),
            None,
        )
        settings_menu = next(
            (
                reply
                for reply in self.replies
                if reply.token == self.settings_menu_token
            ),
            None,
        )
        if (
            len(self.history) != len(self.history_roles)
            or len(set(ids)) != len(ids)
            or len(set(tokens)) != len(tokens)
            or len(set(self.seen_updates)) != len(self.seen_updates)
            or bad_receipt
            or any(
                item.conversation_id > self.conversation_id for item in self.requests
            )
            or any(item.conversation_id > self.conversation_id for item in self.replies)
            or any(
                item.conversation_id > self.conversation_id
                for item in self.voice_inputs
            )
            or len({item.update_id for item in self.voice_inputs})
            != len(self.voice_inputs)
            or len({item.request_id for item in self.voice_inputs})
            != len(self.voice_inputs)
            or (
                self.new_confirmation_token is not None
                and (
                    confirmation is None
                    or confirmation.conversation_id != self.conversation_id
                    or "new_confirm" not in confirmation.actions
                )
            )
            or (
                self.settings_menu_token is not None
                and (
                    settings_menu is None
                    or settings_menu.conversation_id != self.conversation_id
                    or settings_menu.setting_field is None
                    or settings_menu.setting_field != self.editing
                )
            )
        ):
            code = "invalid_state"
            message = "Inconsistent private state"
            raise PydanticCustomError(code, message)
        return self


class Transport(Protocol):
    """Root implements plain-text delivery and keyboard translation."""

    async def send_text(self, chat_id: int, text: str, keyboard: Keyboard) -> int:
        """Return the real Telegram message id; disable parse mode."""
        ...

    async def edit_keyboard(
        self,
        chat_id: int,
        message_id: int,
        keyboard: Keyboard,
    ) -> None:
        """Replace the inline keyboard on this exact message."""
        ...

    async def ack(self, callback_id: str, text: str) -> None:
        """Answer the Telegram callback query without disclosing private data."""
        ...

    async def send_voice(self, chat_id: int, result: VoiceResult) -> int:
        """Resolve the root-owned artifact and send playable voice media."""
        ...


class CompanionGateway(Protocol):
    """Same public chat contracts as the existing HTTP endpoint."""

    async def chat(self, request: ChatRequest) -> ChatResponse:
        """Generate once; exceptions leave a durable unresolved reservation."""
        ...

    async def recover(self, request: ChatRequest) -> ChatResponse | None:
        """Read cached outcome only; NEVER invoke generation or resend."""
        ...


class VoiceGateway(Protocol):
    """Generation and read-only recovery must honor the reserved UUID."""

    async def generate(self, request: VoiceRequest) -> VoiceResult:
        """Persist an audio artifact before returning its reference."""
        ...

    async def recover(self, request: VoiceRequest) -> VoiceResult | None:
        """Read cached artifact only; never regenerate unknown audio."""
        ...
